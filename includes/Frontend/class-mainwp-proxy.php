<?php
/**
 * Burst Statistics – MainWP Proxy (Child Site)
 *
 * Exposes a single REST endpoint (`burst/v1/mainwp-auth`) that the MainWP
 * dashboard calls during a full page load.  It:
 *
 *   1. Verifies the asymmetric signature sent by the dashboard.
 *   2. Resolves the admin user named in the request.
 *   3. Issues (or reuses) a WP Application Password token for that user.
 *   4. Returns the token, a REST nonce, user capabilities, and any
 *      localization data the dashboard React app needs.
 *
 * ── Security model ────────────────────────────────────────────────────────────
 * The dashboard holds an RSA private key; the child stores the matching public
 * key in `mainwp_child_pubkey`.  Every request is signed over the payload
 * `v2|$function|$nonce|$nonce_issued_at|$user|$dashboard_origin` where $nonce
 * is a cryptographically random 32-char hex string generated by the dashboard
 * on each call.  Older dashboards sign only `$function|$nonce|$user`; that
 * legacy signature is accepted until the first v2 signature arrives.
 *
 * Nonces are consumed server-side on first use (via add_option atomicity) and
 * cleaned up after NONCE_TTL_SECONDS.  A second request with the same nonce is
 * rejected even if the signature is still mathematically valid.  Because the
 * issue time is signed, a body replayed after the cleanup fails the TTL check.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * @package Burst\Frontend
 */

namespace Burst\Frontend;

use Burst\Admin\Admin_Options;
use Burst\Admin\DomainTypes\Admin_Option_Category;
use Burst\Traits\Helper;
use Burst\Traits\Sanitize;
use Burst\Traits\Admin_Helper;
use WP_REST_Response;
use WP_REST_Server;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

class MainWP_Proxy {
	use Helper;
	use Sanitize;
	use Admin_Helper;

	/**
	 * Transient key prefix used to persist the Application Password token.
	 * Storing the token avoids creating a new Application Password on every page load.
	 */
	private const APP_TOKEN_META_KEY = 'burst_mainwp_app_token';

	/**
	 * Display name given to the Application Password created for this integration.
	 */
	private const APP_PASSWORD_NAME = 'Burst MainWP';

	/**
	 * Option key prefix used to record consumed nonces.
	 * Format: burst_mainwp_nonce_{32-char-hex}
	 *
	 * Each option stores the Unix timestamp at which the nonce was consumed.
	 * A scheduled event purges the entry after NONCE_TTL_SECONDS + 60s.
	 */
	private const NONCE_OPTION_PREFIX = 'burst_mainwp_nonce_';

	/**
	 * In-process cache of nonces verified during this request.
	 *
	 * WordPress can call permission callbacks and other hooks multiple times
	 * within a single PHP process (e.g. check_auth_permission + is_mainwp_signed_request
	 * both calling verify_signature on the same request body, or separate MainWP_Proxy
	 * instances created by has_admin_access and the REST router). The first call
	 * consumes the nonce via add_option(); subsequent calls for the same nonce
	 * within the same process are allowed through via this cache rather than
	 * being rejected as replays.
	 *
	 * This cache is intentionally not shared across processes or requests —
	 * it lives only for the lifetime of the current PHP process.
	 *
	 * @var array<string, bool>
	 */
	private static array $consumed_nonces = [];

	/**
	 * Verified signed action name for the current request.
	 *
	 * Stored after successful signature verification to ensure subsequent checks
	 * in the same request can verify that the signed function matches expectations.
	 */
	private static ?string $verified_signed_action = null;

	/**
	 * Acceptance window for nonces, in seconds.
	 *
	 * A nonce that arrives more than this many seconds after it was issued is
	 * rejected regardless of cryptographic validity.  The dashboard embeds the
	 * issue timestamp alongside the nonce so the child can enforce this window.
	 *
	 * 5 minutes is generous for a server-to-server call.
	 */
	private const NONCE_TTL_SECONDS = 300;

	/**
	 * Admin option (CORE category) holding a hash of the dashboard public key that sent a v2 signature.
	 *
	 * While the stored hash matches the current key, the legacy `$function|$nonce|$user`
	 * signature is refused, so a captured body cannot be downgraded to it and replayed
	 * after the purge. Reconnecting to another (possibly older) dashboard changes the
	 * key, which lifts the lock for that dashboard.
	 */
	private const SIGNATURE_V2_SEEN_KEY = 'mainwp_signature_v2_seen';

	/**
	 * Register REST routes.  Call from a service-container or direct `init()`.
	 */
	public function init(): void {
		$this->send_cors_headers();
		add_action( 'rest_api_init', [ $this, 'register_routes' ] );
		add_action( 'burst_purge_mainwp_nonce', [ $this, 'purge_nonce_option' ] );
	}

	/**
	 * Register the `burst/v1/mainwp-auth` endpoint.
	 *
	 * The permission callback accepts either a valid MainWP-signed body (the
	 * server-to-server / unauthenticated bootstrap path) or a logged-in user
	 * with the Burst management capability. Subscribers and unauthenticated
	 * unsigned callers are rejected before the route callback runs.
	 */
	public function register_routes(): void {
		register_rest_route(
			'burst/v1',
			'/mainwp-auth',
			[
				'methods'             => WP_REST_Server::CREATABLE,
				'callback'            => [ $this, 'handle_auth_request' ],
				'permission_callback' => [ $this, 'check_auth_permission' ],
			]
		);

		register_rest_route(
			'burst/v1',
			'/mainwp-report-data',
			[
				'methods'             => WP_REST_Server::CREATABLE,
				'callback'            => [ $this, 'handle_report_data_request' ],
				'permission_callback' => [ $this, 'check_report_permission' ],
			]
		);
	}

	/**
	 * Permission gate for the mainwp-auth endpoint.
	 *
	 * Three callers are legitimate, each with its own CSRF defense:
	 *  - MainWP dashboard bootstrap: sends a signed body containing a single-use
	 *    nonce, identified by the X-BURSTMAINWP header. The signature itself is
	 *    the CSRF defense — a browser cannot forge it.
	 *  - Application Password / HTTP Basic Auth: no session cookie is involved,
	 *    so CSRF is structurally impossible.
	 *  - Cookie-authenticated admin (e.g. a same-origin call from the Burst UI):
	 *    must present a valid `burst_nonce` to prove explicit user intent and
	 *    prevent a logged-in admin from being tricked into minting an
	 *    Application Password via a forged cross-origin request.
	 *
	 * @param \WP_REST_Request|null $request The REST request (provided by WP).
	 */
	public function check_auth_permission( ?\WP_REST_Request $request = null ): bool {
		if ( ! current_user_can( 'manage_burst_statistics' ) ) {
			return false;
		}

		// Signed MainWP request: strictly require the 'burst_proxy' action.
		if ( $this->is_mainwp_signed_request( 'burst_proxy' ) ) {
			return true;
		}

		// Application Password authentication from MainWP.
		if ( $this->is_mainwp_authenticated() ) {
			return true;
		}

		// Cookie-auth path: require an explicit burst_nonce.
		$nonce = '';
		if ( $request instanceof \WP_REST_Request ) {
			$header_nonce = $request->get_header( 'x_burst_nonce' );
			if ( is_string( $header_nonce ) && $header_nonce !== '' ) {
				$nonce = $header_nonce;
			} else {
				$param_nonce = $request->get_param( 'burst_nonce' );
				if ( is_string( $param_nonce ) ) {
					$nonce = $param_nonce;
				}
			}
		}

		return $this->verify_nonce( $nonce, 'burst_nonce' );
	}

	/**
	 * Send CORS headers to allow the MainWP dashboard to make cross-origin requests.
	 *
	 * The dashboard's origin is dynamic and must be reflected back in the
	 * `Access-Control-Allow-Origin` header.  We also allow credentials and
	 * necessary headers for the dashboard's REST requests.
	 *
	 * If the request method is OPTIONS, we return a 204 immediately after
	 * sending the headers, without invoking any REST route callbacks, since
	 * this is a preflight request.
	 */
	private function send_cors_headers(): void {
		if ( isset( $_SERVER['HTTP_ACCESS_CONTROL_REQUEST_HEADERS'] ) && ! str_contains( sanitize_text_field( wp_unslash( $_SERVER['HTTP_ACCESS_CONTROL_REQUEST_HEADERS'] ) ), 'x-burstmainwp' ) ) {
			return;
		}

		$origin = isset( $_SERVER['HTTP_ORIGIN'] ) ? sanitize_url( wp_unslash( $_SERVER['HTTP_ORIGIN'] ) ) : '';
		if ( empty( $origin ) ) {
			return;
		}

		if ( empty( get_option( 'mainwp_child_pubkey' ) ) ) {
			return;
		}

		// Only reflect known dashboard origins once pairing has completed.
		$allowed_origin = $this->get_allowed_dashboard_origin();
		$request_origin = $this->normalize_origin( $origin );
		$origin_matches = $allowed_origin !== '' && $request_origin !== '' && hash_equals( $allowed_origin, $request_origin );

		if ( $allowed_origin === '' ) {
			// Unpaired bootstrap: only the mainwp-auth endpoint may negotiate
			// CORS, and credentials are NOT permitted — the first call is
			// signed and must not depend on a logged-in cookie.
			if ( ! $this->is_mainwp_auth_endpoint() ) {
				return;
			}
		} elseif ( ! $origin_matches ) {
			return;
		}

		header_remove( 'Access-Control-Allow-Origin' );
		header_remove( 'Access-Control-Allow-Headers' );
		header_remove( 'Access-Control-Allow-Methods' );
		header_remove( 'Access-Control-Allow-Credentials' );

		header( 'Access-Control-Allow-Origin: ' . $origin );
		if ( $origin_matches ) {
			header( 'Access-Control-Allow-Credentials: true' );
		}
		header( 'Access-Control-Allow-Methods: GET, POST, PUT, PATCH, DELETE, OPTIONS' );
		header( 'Access-Control-Allow-Headers: Authorization, Content-Type, X-WP-Nonce, X-Burst-Auth-Cookie, X-Requested-With, X-Burst-Share-Token, X-BurstMainWP' );
		header( 'Access-Control-Expose-Headers: X-WP-Total, X-WP-TotalPages, Link' );
		header( 'Vary: Origin' );

		if ( isset( $_SERVER['REQUEST_METHOD'] ) && 'OPTIONS' === $_SERVER['REQUEST_METHOD'] ) {
			status_header( 204 );
			exit;
		}
	}

	/**
	 * Normalized dashboard origin stored from the last verified signed request.
	 *
	 * Returns an empty string when no dashboard has paired yet.
	 */
	private function get_allowed_dashboard_origin(): string {
		$stored = (string) get_option( 'burst_mainwp_dashboard_url', '' );
		return $stored === '' ? '' : $this->normalize_origin( $stored );
	}

	/**
	 * Reduce a URL to scheme://host[:port] for stable origin comparison.
	 */
	private function normalize_origin( string $url ): string {
		$parts = wp_parse_url( $url );
		if ( empty( $parts['scheme'] ) || empty( $parts['host'] ) ) {
			return '';
		}

		$origin = strtolower( $parts['scheme'] . '://' . $parts['host'] );
		if ( ! empty( $parts['port'] ) ) {
			$origin .= ':' . (int) $parts['port'];
		}

		return $origin;
	}

	/**
	 * Whether this request targets the mainwp-auth bootstrap endpoint.
	 *
	 * Supports both pretty permalinks and the `?rest_route=` fallback.
	 */
	private function is_mainwp_auth_endpoint(): bool {
		$request_uri = isset( $_SERVER['REQUEST_URI'] ) ? sanitize_text_field( wp_unslash( $_SERVER['REQUEST_URI'] ) ) : '';
		if ( $request_uri !== '' && str_contains( $request_uri, '/burst/v1/mainwp-auth' ) ) {
			return true;
		}

		$query = wp_parse_url( $request_uri, PHP_URL_QUERY );
		if ( ! is_string( $query ) || $query === '' ) {
			return false;
		}

		$query_params = [];
		parse_str( $query, $query_params );

		$rest_route = isset( $query_params['rest_route'] ) ? sanitize_text_field( (string) $query_params['rest_route'] ) : '';
		return $rest_route === '/burst/v1/mainwp-auth';
	}

	/**
	 * Handle an incoming auth request from the MainWP dashboard.
	 *
	 * Authentication, capability check, user-switching, and origin persistence
	 * all happen in `check_auth_permission()`. By the time we get here the
	 * current user is the resolved admin and we only need to mint (or reuse)
	 * the short-lived Application Password.
	 *
	 * @return WP_REST_Response 200 on success; 500 on token creation failure.
	 */
	public function handle_auth_request(): WP_REST_Response {
		$user  = wp_get_current_user();
		$token = $this->get_or_create_app_token( $user->ID );
		if ( is_wp_error( $token ) ) {
			return new WP_REST_Response(
				[
					'error'      => $token->get_error_message(),
					'error_code' => $token->get_error_code(),
					'user_id'    => (int) $user->ID,
				],
				500
			);
		}

		return new WP_REST_Response(
			[
				'token'             => $token,
				'root_url'          => get_rest_url( null, '/' ),
				'localization_data' => $this->localized_settings( [ 'json_translations' => '' ] ),
			],
			200
		);
	}

	/**
	 * Permission check for the mainwp-report-data endpoint.
	 *
	 * Requires the request to originate from MainWP (either signed or authenticated via
	 * Application Password) and the resolved user to have the view_burst_statistics capability.
	 *
	 * @param \WP_REST_Request|null $request The REST request.
	 * @return bool True if permitted, false otherwise.
	 */
	public function check_report_permission( ?\WP_REST_Request $request = null ): bool {
		unset( $request );

		// Only accept Application Password authentication or signed 'burst_report_data' requests.
		if ( ! $this->is_mainwp_authenticated() && ! $this->is_mainwp_signed_request( 'burst_report_data' ) ) {
			return false;
		}

		return current_user_can( 'view_burst_statistics' );
	}

	/**
	 * Handle incoming report data request from MainWP Dashboard.
	 *
	 * @param \WP_REST_Request $request The REST request.
	 */
	public function handle_report_data_request( \WP_REST_Request $request ): \WP_REST_Response {
		$start_date = absint( $request->get_param( 'start_date' ) );
		$end_date   = absint( $request->get_param( 'end_date' ) );

		if ( 0 === $end_date ) {
			$end_date = time();
		}
		if ( 0 === $start_date || $start_date > $end_date ) {
			$start_date = $end_date - ( 30 * DAY_IN_SECONDS );
		}

		$report_data = $this->get_mainwp_report_data( $start_date, $end_date );

		return new \WP_REST_Response(
			[
				'success' => true,
				'data'    => $report_data,
			],
			200
		);
	}

	/**
	 * Generate report data payload for MainWP reporting tokens.
	 *
	 * @param int $start_date Start timestamp.
	 * @param int $end_date   End timestamp.
	 * @return array<string, mixed> Report payload data. Mixed: values include strings, integers, floats, and nested associative arrays.
	 */
	private function get_mainwp_report_data( int $start_date, int $end_date ): array {
		$capabilities = $this->get_datatable_capabilities();

		// 1. Render report blocks on an unsaved Report instance.
		$start_ymd = gmdate( 'Y-m-d', $start_date );
		$end_ymd   = gmdate( 'Y-m-d', $end_date );

		$report             = new \Burst\Admin\Reports\Report();
		$report->name       = __( 'MainWP Performance Report', 'burst-statistics' );
		$report->date_range = \Burst\Admin\Reports\DomainTypes\Report_Date_Range::create_custom_range( $start_ymd, $end_ymd );

		$content_blocks = [
			[ 'id' => \Burst\Admin\Reports\DomainTypes\Report_Content_Block::COMPARE ],
			[ 'id' => \Burst\Admin\Reports\DomainTypes\Report_Content_Block::PAGES ],
			[ 'id' => \Burst\Admin\Reports\DomainTypes\Report_Content_Block::REFERRERS ],
			[ 'id' => \Burst\Admin\Reports\DomainTypes\Report_Content_Block::DEVICES ],
		];

		// Without the sales capability the block is not rendered at all, so sales data
		// cannot reach the tables, the pro data or the AI summary prompt.
		$sales_cap = $capabilities['sales_products'] ?? 'view_sales_burst_statistics';
		if ( current_user_can( $sales_cap ) && \Burst\burst_loader()->integrations->has_active_ecommerce_integration() ) {
			$content_blocks[] = [ 'id' => \Burst\Admin\Reports\DomainTypes\Report_Content_Block::SALES ];
		}

		$report->content = $content_blocks;

		$reports         = new \Burst\Admin\Reports\Reports();
		$rendered_blocks = $reports->render_report_blocks( $report );

		// Metrics and browsers use the same whole-day range as the blocks.
		$dates      = \Burst\Admin\Reports\DomainTypes\Report_Date_Range::resolve_block_dates( null, $report );
		$start_date = (int) $dates['start'];
		$end_date   = (int) $dates['end'];

		// 2. Metrics (gated by statistics_pages capability).
		$pages_cap = $capabilities['statistics_pages'] ?? 'view_burst_statistics';
		$metrics   = current_user_can( $pages_cap ) ? $this->build_summary_metrics( $start_date, $end_date ) : [];

		// 3. Tables (gated by each block's capability).
		$tables = $this->build_report_tables( $start_date, $end_date, $rendered_blocks, $capabilities );

		// 4. Pro data (pass rendered blocks and report to filter).
		$pro_data = apply_filters( 'burst_mainwp_report_data_pro', [], $start_date, $end_date, $rendered_blocks, $report );
		if ( ! is_array( $pro_data ) ) {
			$pro_data = [];
		}

		// Ensure sales data is stripped if caller lacks sales capability.
		if ( ! current_user_can( $sales_cap ) ) {
			unset( $pro_data['sales'], $pro_data['ecommerce'] );
		}

		$date_format          = (string) get_option( 'date_format', 'Y-m-d' );
		$start_date_formatted = wp_date( $date_format, $start_date );
		$end_date_formatted   = wp_date( $date_format, $end_date );

		return [
			'start_date'           => $start_date,
			'end_date'             => $end_date,
			'start_date_formatted' => $start_date_formatted,
			'end_date_formatted'   => $end_date_formatted,
			'metrics'              => $metrics,
			'tables'               => $tables,
			'pro'                  => $pro_data,
		];
	}

	/**
	 * Retrieve datatable capabilities declared in App::get_datatable_config().
	 *
	 * @return array<string, string> Map of datatable_id => capability.
	 */
	private function get_datatable_capabilities(): array {
		if ( ! class_exists( '\Burst\Admin\App\App' ) ) {
			return [
				'statistics_pages'     => 'view_burst_statistics',
				'statistics_referrers' => 'view_burst_statistics',
				'sales_products'       => 'view_sales_burst_statistics',
			];
		}

		$app    = new \Burst\Admin\App\App();
		$config = $app->get_datatable_config();
		$caps   = [];
		foreach ( $config as $id => $item ) {
			if ( isset( $item['capability'] ) && is_string( $item['capability'] ) ) {
				$caps[ $id ] = $item['capability'];
			}
		}

		return $caps;
	}

	/**
	 * Build summary metrics for the MainWP report payload.
	 *
	 * @param int $start_date Start timestamp.
	 * @param int $end_date   End timestamp.
	 * @return array<string, int|float|string> Summary metrics.
	 */
	private function build_summary_metrics( int $start_date, int $end_date ): array {
		$stats_data = new \Burst\Admin\Statistics\Statistics_Data();
		$compare    = $stats_data->get_compare_data(
			[
				'date_start' => $start_date,
				'date_end'   => $end_date,
			]
		);
		$current    = $compare['current'] ?? [];

		$pageviews           = (int) ( $current['pageviews'] ?? 0 );
		$visitors            = (int) ( $current['visitors'] ?? 0 );
		$sessions            = (int) ( $current['sessions'] ?? 0 );
		$bounces             = (int) ( $current['bounced_sessions'] ?? 0 );
		$first_time_visitors = (int) ( $current['first_time_visitors'] ?? 0 );
		$bounce_rate         = (float) ( $current['bounce_rate'] ?? 0 );

		// avg_time_on_page from get_compare_data() is in milliseconds; convert to seconds.
		$avg_time_ms      = (float) ( $current['avg_time_on_page'] ?? 0 );
		$avg_time_seconds = (int) round( $avg_time_ms / 1000 );

		return [
			'pageviews'             => $pageviews,
			'pageviews_formatted'   => number_format_i18n( $pageviews ),
			'visitors'              => $visitors,
			'visitors_formatted'    => number_format_i18n( $visitors ),
			'sessions'              => $sessions,
			'sessions_formatted'    => number_format_i18n( $sessions ),
			'bounces'               => $bounces,
			'bounces_formatted'     => number_format_i18n( $bounces ),
			'first_time_visitors'   => $first_time_visitors,
			'first_time_formatted'  => number_format_i18n( $first_time_visitors ),
			'bounce_rate'           => $bounce_rate,
			'bounce_rate_formatted' => round( $bounce_rate, 1 ) . '%',
			'avg_time_seconds'      => $avg_time_seconds,
			'avg_time_formatted'    => $this->format_duration( $avg_time_seconds ),
		];
	}

	/**
	 * Build tables dictionary for the MainWP report payload, gated by capabilities from get_datatable_config().
	 *
	 * @param int                                 $start_date      Start timestamp.
	 * @param int                                 $end_date        End timestamp.
	 * @param array<string, array<string, mixed>> $rendered_blocks Pre-rendered report blocks. Mixed: block data contains strings, numbers, and nested array properties.
	 * @param array<string, string>               $capabilities    Map of table/metric to capability.
	 * @return array<string, string> Table HTML strings keyed by table identifier.
	 */
	private function build_report_tables( int $start_date, int $end_date, array $rendered_blocks, array $capabilities ): array {
		$tables = [];

		$pages_cap = $capabilities['statistics_pages'] ?? 'view_burst_statistics';
		if ( current_user_can( $pages_cap ) ) {
			$raw_pages           = (string) ( $rendered_blocks['pages']['table'] ?? ( $rendered_blocks[ \Burst\Admin\Reports\DomainTypes\Report_Content_Block::MOST_VISITED_PAGES ]['table'] ?? '' ) );
			$tables['top_pages'] = $this->wrap_report_table( $raw_pages );
		}

		$referrers_cap = $capabilities['statistics_referrers'] ?? 'view_burst_statistics';
		if ( current_user_can( $referrers_cap ) ) {
			$raw_referrers           = (string) ( $rendered_blocks['referrers']['table'] ?? ( $rendered_blocks[ \Burst\Admin\Reports\DomainTypes\Report_Content_Block::TOP_REFERRERS ]['table'] ?? '' ) );
			$tables['top_referrers'] = $this->wrap_report_table( $raw_referrers );
		}

		$devices_cap = $capabilities['statistics_devices'] ?? 'view_burst_statistics';
		if ( current_user_can( $devices_cap ) ) {
			$raw_devices        = (string) ( $rendered_blocks['devices']['table'] ?? ( $rendered_blocks[ \Burst\Admin\Reports\DomainTypes\Report_Content_Block::DEVICES ]['table'] ?? '' ) );
			$tables['devices']  = $this->wrap_report_table( $raw_devices );
			$tables['browsers'] = $this->build_browsers_table( $start_date, $end_date );
		}

		$sales_cap = $capabilities['sales_products'] ?? 'view_sales_burst_statistics';
		if ( current_user_can( $sales_cap ) && isset( $rendered_blocks['sales']['table'] ) ) {
			$tables['sales'] = $this->wrap_report_table( (string) $rendered_blocks['sales']['table'] );
		}

		return $tables;
	}

	/**
	 * Build HTML table for top browsers breakdown.
	 *
	 * @param int $start_date Start timestamp.
	 * @param int $end_date   End timestamp.
	 * @return string HTML table or empty string.
	 */
	private function build_browsers_table( int $start_date, int $end_date ): string {
		$stats_data      = new \Burst\Admin\Statistics\Statistics_Data();
		$browsers_header = [ __( 'Browser', 'burst-statistics' ), __( 'Sessions', 'burst-statistics' ) ];
		$browsers_qd     = \Burst\Admin\Statistics\Statistics_Query::create( 'mainwp_report_browsers' )
			->date_range( $start_date, $end_date )
			->with( 'sessions' )
			->select( [ 'browser_id' ] )
			->select_raw( 'sessions.browser_id, COUNT(DISTINCT sessions.id) AS count' )
			->where_raw( 'sessions.browser_id > 0' )
			->group_by( 'browser_id' )
			->order_by( 'count DESC' )
			->limit( 5 );
		$browser_db_rows = $browsers_qd->fetch( ARRAY_A );
		$browsers_rows   = [];
		foreach ( $browser_db_rows as $row ) {
			$browser_name = $stats_data->get_lookup_table_name_by_id( 'browser', (int) ( $row['browser_id'] ?? 0 ) );
			if ( ! empty( $browser_name ) ) {
				$browsers_rows[] = [ $browser_name, number_format_i18n( (int) ( $row['count'] ?? 0 ) ) ];
			}
		}

		return $this->render_report_table( $browsers_header, $browsers_rows );
	}

	/**
	 * Format a duration in seconds into a human-readable string (e.g. "45s", "2m 14s").
	 *
	 * @param int $seconds Duration in seconds.
	 * @return string Formatted duration string.
	 */
	private function format_duration( int $seconds ): string {
		if ( $seconds < 60 ) {
			return $seconds . 's';
		}

		$minutes = (int) floor( $seconds / 60 );
		$rem     = $seconds % 60;

		return sprintf( '%dm %02ds', $minutes, $rem );
	}

	/**
	 * Wrap raw table rows in a styled table element if not already wrapped.
	 *
	 * @param string $rows_html Raw table rows HTML.
	 * @return string Styled table HTML or empty string.
	 */
	private function wrap_report_table( string $rows_html ): string {
		$trimmed = trim( $rows_html );
		if ( '' === $trimmed ) {
			return '';
		}

		if ( str_starts_with( strtolower( $trimmed ), '<table' ) ) {
			return $trimmed;
		}

		return '<table class="burst-report-table" style="width: 100%; border-collapse: collapse; margin: 8px 0 16px 0;">'
			. $trimmed
			. '</table>';
	}

	/**
	 * Render HTML table for report blocks.
	 *
	 * @param array<int, string>                   $header Table header titles.
	 * @param array<int, array<int|string, mixed>> $rows   Table rows. Mixed: cell values can be strings, numbers, or null for unknown values.
	 * @return string HTML table string or empty string if no rows.
	 */
	private function render_report_table( array $header, array $rows ): string {
		if ( empty( $rows ) ) {
			return '';
		}

		$table_data           = $rows;
		$table_data['header'] = $header;
		$table_rows           = \Burst\Admin\Reports\Reports::format_array_as_table( $table_data );

		return $this->wrap_report_table( $table_rows );
	}

	/**
	 * Determine if the incoming request is a valid, signed MainWP request.
	 *
	 * Used as a gatekeeper in admin screens shared between regular WP users
	 * and the MainWP dashboard, to conditionally show/hide sensitive data.
	 *
	 * @param string|null $expected_action Expected action name (e.g. 'burst_proxy', 'burst_report_data').
	 * @return bool True when the request carries a valid MainWP signature.
	 */
	public function is_mainwp_signed_request( ?string $expected_action = null ): bool {
		if ( self::$verified_signed_action !== null ) {
			if ( $expected_action !== null && self::$verified_signed_action !== $expected_action ) {
				return false;
			}
			return true;
		}

		$request_body = file_get_contents( 'php://input' );
		$body         = json_decode( $request_body, true );

		if ( empty( $body ) || ! is_array( $body ) ) {
			return false;
		}

		return $this->authenticate_signed_body( $body, $expected_action );
	}

	/**
	 * Verify a decoded signed body and log in the MainWP user it names.
	 *
	 * Side effects: consumes the nonce, sets the current user, caches the
	 * verified action for this request and, on auth calls, stores the
	 * dashboard origin.
	 *
	 * @param array<string, mixed> $body            Decoded JSON body. Mixed: values are strings and integers from the dashboard.
	 * @param string|null          $expected_action Function the body must be signed for, or null for any.
	 * @return bool True when the signature is valid and the user may manage Burst.
	 */
	private function authenticate_signed_body( array $body, ?string $expected_action ): bool {
		if ( ! $this->verify_signature( $body, $expected_action ) ) {
			return false;
		}

		$username = sanitize_user( $body['user'] ?? '' );
		$user     = get_user_by( 'login', $username );

		if ( ! $user || ! user_can( $user, 'manage_burst_statistics' ) ) {
			return false;
		}

		// Cache only after the user check: a cached action short-circuits later calls to true.
		self::$verified_signed_action = (string) ( $body['function'] ?? '' );

		wp_set_current_user( $user->ID );

		// Persist the dashboard origin for CORS reflection on subsequent
		// browser requests from the React app, only on auth calls.
		if ( 'burst_proxy' === self::$verified_signed_action ) {
			$body_origin       = is_string( $body['dashboard_origin'] ?? null ) ? sanitize_url( $body['dashboard_origin'] ) : '';
			$normalized_origin = $this->normalize_origin( $body_origin );
			if ( $normalized_origin !== '' ) {
				update_option( 'burst_mainwp_dashboard_url', $normalized_origin, false );
			}
		}

		return true;
	}

	/**
	 * Determine if the current request is authenticated as the MainWP dashboard.
	 *
	 * Used in REST route permission callbacks to restrict access to routes that
	 * should only be reachable via the MainWP Application Password credential.
	 *
	 * @return bool True when the request is authenticated as MainWP.
	 */
	public function is_mainwp_authenticated(): bool {
		$auth_header = sanitize_text_field( wp_unslash( $_SERVER['HTTP_AUTHORIZATION'] ?? $_SERVER['REDIRECT_HTTP_AUTHORIZATION'] ?? '' ) );

		if ( empty( $auth_header ) || stripos( $auth_header, 'basic ' ) !== 0 ) {
			return false;
		}

		// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_decode
		$credentials = base64_decode( substr( $auth_header, 6 ), true );
		if ( ! $credentials ) {
			return false;
		}

		$parts = explode( ':', $credentials, 2 );
		if ( count( $parts ) !== 2 ) {
			return false;
		}

		if ( ! function_exists( 'wp_validate_application_password' ) ) {
			return false;
		}

		// Save and restore the original PHP_AUTH_* server values so that populating
		// them here (required by wp_validate_application_password) does not bleed into
		// any other auth checks that may run later in the same request.
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized,WordPress.Security.ValidatedSanitizedInput.MissingUnslash
		$saved_auth_user = $_SERVER['PHP_AUTH_USER'] ?? null;
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized,WordPress.Security.ValidatedSanitizedInput.MissingUnslash
		$saved_auth_pw = $_SERVER['PHP_AUTH_PW'] ?? null;

		// We are *writing* to $_SERVER so wp_validate_application_password() can read the
		// credentials. $parts values originate from the sanitized $auth_header above.
		// Sanitizing further (e.g. sanitize_text_field) would corrupt the password.
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized,WordPress.Security.ValidatedSanitizedInput.MissingUnslash
		$_SERVER['PHP_AUTH_USER'] = $parts[0];
		// phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized,WordPress.Security.ValidatedSanitizedInput.MissingUnslash
		$_SERVER['PHP_AUTH_PW'] = $parts[1];

		// wp_validate_application_password() only operates when WordPress considers the
		// request to be a REST API context. This function is called from has_admin_access(),
		// which runs before REST routes are loaded — it is the gate that decides whether to
		// load them. At that early point WordPress has not yet identified the request as an
		// API context, so without this filter wp_validate_application_password() returns
		// nothing and the credential check silently fails, resulting in a 404 "route not found"
		// because the REST endpoint files are never loaded. The filter is scoped tightly and
		// removed immediately after the call.
		add_filter( 'application_password_is_api_request', '__return_true', 99 );
		$validated_user_id = wp_validate_application_password( false );
		remove_filter( 'application_password_is_api_request', '__return_true', 99 );

		if ( $saved_auth_user !== null ) {
			$_SERVER['PHP_AUTH_USER'] = $saved_auth_user;
		} else {
			unset( $_SERVER['PHP_AUTH_USER'] );
		}
		if ( $saved_auth_pw !== null ) {
			$_SERVER['PHP_AUTH_PW'] = $saved_auth_pw;
		} else {
			unset( $_SERVER['PHP_AUTH_PW'] );
		}

		if ( empty( $validated_user_id ) ) {
			return false;
		}

		// wp_validate_application_password() validates both the username and the
		// application password credential atomically and returns the authenticated user's
		// ID. We use that ID directly — no secondary username comparison is needed or
		// safe, because the validated ID already proves the credentials matched.
		$authenticated_user = get_user_by( 'id', (int) $validated_user_id );
		if ( ! $authenticated_user instanceof \WP_User ) {
			return false;
		}

		if ( ! user_can( $authenticated_user, 'manage_burst_statistics' ) ) {
			return false;
		}

		wp_set_current_user( $authenticated_user->ID );
		return true;
	}

	// ── Nonce Management ──────────────────────────────────────────────────────

	/**
	 * Consume a nonce atomically, rejecting it if already used or expired.
	 *
	 * The body must include a `nonce_issued_at` Unix timestamp set by the
	 * dashboard at signing time.  We reject nonces issued more than
	 * NONCE_TTL_SECONDS ago so a captured body cannot be replayed after the
	 * window closes even if it was never consumed.
	 *
	 * `add_option()` returns false when the key already exists, giving us a
	 * cheap atomic compare-and-set without a DB transaction.
	 *
	 * @param string $nonce     The 32-char hex nonce from the signed body.
	 * @param int    $issued_at Unix timestamp embedded in the body by the dashboard.
	 * @return bool True if the nonce was freshly consumed; false otherwise.
	 */
	private function consume_nonce( string $nonce, int $issued_at ): bool {
		// If this nonce was already consumed earlier in the same PHP process
		// (e.g. check_auth_permission and is_mainwp_signed_request both firing
		// on the same request body), allow it through without hitting the DB again.
		if ( isset( self::$consumed_nonces[ $nonce ] ) ) {
			return true;
		}

		// Reject nonces that are outside the acceptance window.
		$age = time() - $issued_at;
		if ( $age < 0 || $age > self::NONCE_TTL_SECONDS ) {
			self::error_log( sprintf( 'MainWP nonce rejected: age %ds outside TTL window.', $age ) );
			return false;
		}

		// Validate the nonce looks like a 32-char lowercase hex string.
		if ( ! preg_match( '/^[0-9a-f]{32}$/', $nonce ) ) {
			return false;
		}

		$option_key = self::NONCE_OPTION_PREFIX . $nonce;

		// add_option() is a no-op (returns false) when the key already exists —
		// this is our atomic single-use enforcement across processes.
		$consumed = add_option( $option_key, time(), '', false );

		if ( $consumed ) {
			// Record in-process so subsequent same-request calls don't false-positive.
			self::$consumed_nonces[ $nonce ] = true;

			// Schedule cleanup — give a little extra headroom beyond the TTL.
			wp_schedule_single_event(
				time() + self::NONCE_TTL_SECONDS + 60,
				'burst_purge_mainwp_nonce',
				[ $option_key ]
			);
		}

		return $consumed;
	}

	/**
	 * Delete a single consumed nonce option.
	 *
	 * Hooked to the `burst_purge_mainwp_nonce` scheduled event.
	 *
	 * @param string $option_key The option key to delete.
	 */
	public function purge_nonce_option( string $option_key ): void {
		if ( str_starts_with( $option_key, self::NONCE_OPTION_PREFIX ) ) {
			delete_option( $option_key );
		}
	}

	// ── Signature Verification ────────────────────────────────────────────────

	/**
	 * Verify the asymmetric signature attached to a dashboard request.
	 *
	 * Expected signed payload (`mainwpsignature_v2`):
	 * `v2|$function|$nonce|$nonce_issued_at|$user|$dashboard_origin`.
	 * Older dashboards only send `mainwpsignature` over `$function|$nonce|$user`;
	 * that legacy signature is accepted until the current dashboard key has sent a v2 signature.
	 *
	 * The dashboard generates `$nonce` as `bin2hex(random_bytes(16))` — a
	 * 32-char cryptographically random hex string — and embeds `nonce_issued_at`
	 * (Unix timestamp) alongside it.  Signing the issue time keeps a body that
	 * is replayed after the nonce purge outside the TTL window.
	 *
	 * `verifylib` == 1 → phpseclib path (SHA-1 + PKCS#1 v1.5).
	 * `verifylib` == 0 → standard OpenSSL (SHA-256).
	 *
	 * Side effects: consumes the nonce, and records the first valid v2 signature
	 * in the CORE admin options.
	 *
	 * @param array       $body            Decoded JSON body from the dashboard.
	 * @param string|null $expected_action Function the body must be signed for, or null for any.
	 * @return bool True when the signature is valid and the nonce is fresh.
	 */
	private function verify_signature( array $body, ?string $expected_action = null ): bool {
		$pubkey_stored    = get_option( 'mainwp_child_pubkey' );
		$signature_v2_b64 = is_string( $body['mainwpsignature_v2'] ?? null ) ? $body['mainwpsignature_v2'] : '';
		$signature_b64    = '' !== $signature_v2_b64 ? $signature_v2_b64 : ( $body['mainwpsignature'] ?? '' );
		$nonce            = is_string( $body['nonce'] ?? null ) ? $body['nonce'] : '';
		$issued_at        = isset( $body['nonce_issued_at'] ) ? (int) $body['nonce_issued_at'] : 0;
		$function         = $body['function'] ?? '';
		$user_raw         = is_string( $body['user'] ?? null ) ? $body['user'] : '';
		$origin_raw       = is_string( $body['dashboard_origin'] ?? null ) ? $body['dashboard_origin'] : '';
		$use_seclib       = ! empty( $body['verifylib'] );

		if ( empty( $pubkey_stored ) || empty( $signature_b64 ) || $nonce === '' || $issued_at === 0 || empty( $function ) || $user_raw === '' ) {
			return false;
		}

		if ( $expected_action !== null && $function !== $expected_action ) {
			return false;
		}

		$is_v2       = '' !== $signature_v2_b64;
		$pubkey_hash = hash( 'sha256', (string) $pubkey_stored );
		$v2_key_hash = Admin_Options::get( Admin_Option_Category::CORE, self::SIGNATURE_V2_SEEN_KEY, '' );
		if ( ! $is_v2 && $v2_key_hash === $pubkey_hash ) {
			self::error_log( 'MainWP legacy signature rejected: this dashboard already sends v2 signatures.' );
			return false;
		}

		// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_decode
		$pubkey_pem = base64_decode( $pubkey_stored, true );
		if ( empty( $pubkey_pem ) || ! str_contains( $pubkey_pem, '-----BEGIN' ) ) {
			self::error_log( 'Pubkey decode failed or value is not a PEM block.' );
			return false;
		}

		$public_key = openssl_pkey_get_public( $pubkey_pem );
		if ( false === $public_key ) {
			self::error_log( 'OpenSSL could not parse the stored MainWP public key.' );
			return false;
		}

		// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_decode
		$signature = base64_decode( $signature_b64, true );
		if ( false === $signature ) {
			return false;
		}

		$algorithm    = $use_seclib ? OPENSSL_ALGO_SHA1 : OPENSSL_ALGO_SHA256;
		$sign_payload = $is_v2
			? implode( '|', [ 'v2', $function, $nonce, (string) $issued_at, $user_raw, $origin_raw ] )
			: $function . '|' . $nonce . '|' . $user_raw;
		$result       = openssl_verify( $sign_payload, $signature, $public_key, $algorithm );

		if ( 1 !== $result ) {
			$msg = openssl_error_string();
			while ( $msg ) {
				self::error_log( 'OpenSSL verification error: ' . $msg );
				$msg = openssl_error_string();
			}
			return false;
		}

		// Signature is cryptographically valid — enforce single-use and TTL.
		if ( ! $this->consume_nonce( $nonce, $issued_at ) ) {
			self::error_log( 'MainWP nonce rejected (already consumed or expired): ' . $nonce );
			return false;
		}

		if ( $is_v2 && $v2_key_hash !== $pubkey_hash ) {
			Admin_Options::update( Admin_Option_Category::CORE, self::SIGNATURE_V2_SEEN_KEY, $pubkey_hash );
		}

		return true;
	}

	// ── Token Management ──────────────────────────────────────────────────────

	/**
	 * Return an existing short-lived Application Password token for this user,
	 * or create a fresh one.
	 *
	 * A transient (1-hour TTL) holds the plain-text token so it is never stored
	 * long-term.  When the transient expires the old Application Password is
	 * deleted and a new one is minted on the next request.
	 *
	 * @param int $user_id WP user ID.
	 * @return string|\WP_Error Base64 `user:password` token, or WP_Error on failure.
	 */
	private function get_or_create_app_token( int $user_id ): string|\WP_Error {
		if ( $user_id <= 0 ) {
			return new \WP_Error( 'invalid_mainwp_user', 'Could not resolve MainWP user for app password generation.' );
		}

		$transient_key = self::APP_TOKEN_META_KEY . '_' . $user_id;
		$cached        = get_transient( $transient_key );
		if ( ! empty( $cached ) ) {
			return $cached;
		}

		if ( ! class_exists( 'WP_Application_Passwords' ) ) {
			return new \WP_Error( 'app_passwords_unavailable', 'Application Passwords not available.' );
		}

		// Delete any existing Burst MainWP app passwords to prevent accumulation.
		$existing = \WP_Application_Passwords::get_user_application_passwords( $user_id );
		foreach ( $existing as $app_password ) {
			if ( $app_password['name'] === self::APP_PASSWORD_NAME ) {
				\WP_Application_Passwords::delete_application_password( $user_id, $app_password['uuid'] );
			}
		}

		$result = \WP_Application_Passwords::create_new_application_password(
			$user_id,
			[ 'name' => self::APP_PASSWORD_NAME ]
		);

		if ( is_wp_error( $result ) ) {
			return $result;
		}

		$user = get_userdata( $user_id );
		// phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_encode
		$token = base64_encode( $user->user_login . ':' . $result[0] );

		// Store for 1 hour only — plain-text token never persisted long-term.
		set_transient( $transient_key, $token, HOUR_IN_SECONDS );

		return $token;
	}
